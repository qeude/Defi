#!/usr/bin/env python3
"""Summarizes mutation results by bug type and by area, and lists the survivors.

Mutants that do not compile or whose line moved are excluded from the score. Rows listed in
Tests/Mutation/equivalent.tsv (id, reason) are equivalent mutants: no observable behavior
changes, so they are excluded too, with their reason shown.

    report.py [--results .build/mutation/results.tsv] [--out docs/testing/mutation-results.md]
"""
import argparse
import csv
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]


def read(path):
    if not Path(path).exists():
        return []
    with open(path, newline="") as handle:
        return list(csv.DictReader(handle, delimiter="\t", quoting=csv.QUOTE_NONE, escapechar="\\"))


def table(rows, key):
    stats = defaultdict(lambda: [0, 0])
    for row in rows:
        stats[row[key]][0] += row["verdict"] == "killed"
        stats[row[key]][1] += 1
    lines = [f"| {key.capitalize()} | Killed | Score |", "|---|---|---|"]
    for name, (killed, total) in sorted(stats.items(), key=lambda item: -item[1][1]):
        lines.append(f"| {name} | {killed} of {total} | {100 * killed / total:.0f}% |")
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--results", default=".build/mutation/results.tsv")
    parser.add_argument("--out", default="docs/testing/mutation-results.md")
    args = parser.parse_args()
    results = read(ROOT / args.results)
    equivalent = {row["id"]: row["reason"] for row in read(ROOT / "Tests/Mutation/equivalent.tsv")}
    scored = [r for r in results if r["verdict"] in ("killed", "survived") and r["id"] not in equivalent]
    skipped = [r for r in results if r["verdict"].startswith("skip")]
    killed = sum(r["verdict"] == "killed" for r in scored)
    lines = [
        "# Mutation results",
        "",
        "Generated by `script/mutation/report.py` from the last `make mutate` run.",
        "",
        f"**{killed} of {len(scored)} scored mutants killed ({100 * killed / max(len(scored), 1):.0f}%).**",
        f"{len(skipped)} did not compile or no longer matched and are excluded; "
        f"{len(equivalent)} are listed as equivalent.",
        "",
        "## By bug type",
        "",
        table(scored, "type"),
        "",
        "## By area",
        "",
        table(scored, "area"),
        "",
        "## Survivors",
        "",
        "| Type | Area | Mutant |",
        "|---|---|---|",
    ]
    lines += [f"| {r['type']} | {r['area']} | `{r['id']}` {r['description']} |"
              for r in sorted(scored, key=lambda r: (r["type"], r["area"])) if r["verdict"] == "survived"]
    if equivalent:
        lines += ["", "## Equivalent mutants", "", "| Mutant | Reason |", "|---|---|"]
        lines += [f"| `{key}` | {reason} |" for key, reason in sorted(equivalent.items())]
    (ROOT / args.out).write_text("\n".join(lines) + "\n")
    print(f"{killed}/{len(scored)} killed -> {args.out}")


if __name__ == "__main__":
    main()
